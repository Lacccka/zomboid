local function QPSR_contains(value, token)
    return string.find(value, token, 1, true) ~= nil
end

local function QPSR_normalizeLanguage(rawLanguage)
    local value = string.upper(tostring(rawLanguage or ""))

    if QPSR_contains(value, "PTBR") or
       QPSR_contains(value, "PORTUGUESEBRAZIL") or
       QPSR_contains(value, "PORTUGUESE (BRAZIL)") or
       QPSR_contains(value, "BRAZIL") or
       QPSR_contains(value, "BRASIL") then
        return "PTBR"
    end

    if QPSR_contains(value, "RUSSIAN") or value == "RU" or
       QPSR_contains(value, "_RU") then
        return "RU"
    end

    if QPSR_contains(value, "CHINESE") or
       QPSR_contains(value, "SIMPLIFIED") or
       value == "CN" or value == "CHS" then
        return "CN"
    end

    if QPSR_contains(value, "FRENCH") or
       QPSR_contains(value, "FRAN") or
       value == "FR" then
        return "FR"
    end

    if QPSR_contains(value, "SPANISH") or
       QPSR_contains(value, "ESPAN") or
       value == "ES" then
        return "ES"
    end

    return "EN"
end

function QPSR_I18N.getLanguageCode()
    local rawLanguage = ""

    local okTranslator, translatorLanguage = pcall(function()
        local language = Translator.getLanguage()
        if language then
            return tostring(language:name())
        end
        return ""
    end)

    if okTranslator and translatorLanguage and translatorLanguage ~= "" then
        rawLanguage = translatorLanguage
    else
        local okCore, coreLanguage = pcall(function()
            return tostring(getCore():getOptionLanguageName() or "")
        end)

        if okCore and coreLanguage then
            rawLanguage = coreLanguage
        end
    end

    return QPSR_normalizeLanguage(rawLanguage)
end

local function QPSR_replacePlain(text, token, replacement)
    local result = tostring(text or "")
    local search = tostring(token or "")
    local value = tostring(replacement or "")

    if search == "" then
        return result
    end

    local startIndex = 1

    while true do
        local firstIndex, lastIndex = string.find(
            result,
            search,
            startIndex,
            true
        )

        if firstIndex == nil then
            break
        end

        result = string.sub(result, 1, firstIndex - 1)
            .. value
            .. string.sub(result, lastIndex + 1)

        startIndex = firstIndex + string.len(value)
    end

    return result
end

local function QPSR_applyArguments(text, ...)
    local result = tostring(text or "")
    local args = {...}

    for index, value in ipairs(args) do
        result = QPSR_replacePlain(
            result,
            "%" .. tostring(index),
            tostring(value or "")
        )
    end

    return result
end

function QPSR_I18N.getText(key, ...)
    local languageCode = QPSR_I18N.getLanguageCode()
    local languageTable = TRANSLATIONS[languageCode] or TRANSLATIONS.EN
    local value = languageTable[key] or TRANSLATIONS.EN[key] or tostring(key)

    return QPSR_applyArguments(value, ...)
end

-- QPSR_KAHLUA_SAFE_CONTAINER_LABEL_V1
-- Project Zomboid's Kahlua runtime can fail when string.gsub() uses a Lua
-- callback as the replacement value. Fridge/freezer labels bypassed this
-- path, which is why only those compartments reached the context menu.
-- Keep container-label formatting to simple string operations.
local function QPSR_prettifyContainerType(containerType)
    local value = tostring(containerType or "")
    value = string.gsub(value, "_", " ")
    value = value:match("^%s*(.-)%s*$") or ""

    if value == "" then
        return ""
    end

    local first = string.sub(value, 1, 1)
    local rest = string.sub(value, 2)

    if first == "" then
        return value
    end

    return string.upper(first) .. rest
end

function QPSR_I18N.getContainerLabel(containerType, containerIndex)
    local value = string.lower(tostring(containerType or ""))

    if value == "fridge" or value == "refrigerator" then
        return QPSR_I18N.getText("UI_QPSR_ContainerFridge")
    end

    if value == "freezer" then
        return QPSR_I18N.getText("UI_QPSR_ContainerFreezer")
    end

    local pretty = QPSR_prettifyContainerType(containerType)
    if pretty ~= "" then
        return pretty
    end

    return QPSR_I18N.getText(
        "UI_QPSR_ContainerFallback",
        (tonumber(containerIndex) or 0) + 1
    )
end

